create or replace view FINANCE_DB.CORE.V_SALES_PRODUCT_DATASET_STD(
	BUSINESS_LINE,
	PRODUCT,
	YEAR,
	SEASON,
	QUANTITY,
	PRICE,
	COST,
	REVENUE,
	COGS,
	GROSS_PROFIT
) as 
SELECT 
    Business_Line,
	PRODUCT ,
	YEAR ,
	SEASON ,
	QUANTITY ,
	PRICE ,
	COST ,
    QUANTITY * PRICE AS REVENUE,
    QUANTITY * COST AS COGS,
    (QUANTITY * PRICE) - (QUANTITY * COST) AS GROSS_PROFIT
    FROM RAW.SALES_PRODUCT T;